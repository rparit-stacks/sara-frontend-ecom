export type AutoSelectReason = {
  /** Permission the user intentionally selected */
  becauseOfCode: string;
  becauseOfName: string;
  /** Permission that was auto-added */
  autoCode: string;
  autoName: string;
};

function requiredOf(code: string): string[] {
  return PERMISSION_REQUIRES[code] || [];
}

/** Expand selected codes with all transitive requirements. */
export function expandPermissionCodes(codes: Iterable<string>): Set<string> {
  const out = new Set<string>();
  const stack = [...codes];
  while (stack.length) {
    const c = stack.pop()!;
    if (out.has(c)) continue;
    out.add(c);
    for (const req of requiredOf(c)) {
      if (!out.has(req)) stack.push(req);
    }
  }
  return out;
}

/**
 * After turning ON `turnedOnCodes`, return next selected ids + auto-added reasons
 * (only for codes that were not already selected).
 */
export function applyPermissionSelect(opts: {
  selectedIds: Set<number>;
  turnedOnIds: number[];
  idToCode: Map<number, string>;
  codeToId: Map<string, number>;
  codeToName: Map<string, string>;
}): { nextIds: Set<number>; reasons: AutoSelectReason[] } {
  const { selectedIds, turnedOnIds, idToCode, codeToId, codeToName } = opts;
  const beforeCodes = new Set(
    [...selectedIds].map((id) => idToCode.get(id)).filter((c): c is string => !!c),
  );

  const turnedOnCodes = turnedOnIds
    .map((id) => idToCode.get(id))
    .filter((c): c is string => !!c);

  const expanded = expandPermissionCodes([...beforeCodes, ...turnedOnCodes]);
  const nextIds = new Set<number>();
  for (const code of expanded) {
    const id = codeToId.get(code);
    if (id != null) nextIds.add(id);
  }
  // Keep any selected ids that somehow have no code mapping
  for (const id of selectedIds) {
    if (!idToCode.has(id)) nextIds.add(id);
  }
  for (const id of turnedOnIds) nextIds.add(id);

  const reasons: AutoSelectReason[] = [];
  const seenAuto = new Set<string>();

  for (const becauseOfCode of turnedOnCodes) {
    const needed = expandPermissionCodes([becauseOfCode]);
    for (const autoCode of needed) {
      if (autoCode === becauseOfCode) continue;
      if (beforeCodes.has(autoCode)) continue;
      if (turnedOnCodes.includes(autoCode)) continue;
      if (seenAuto.has(autoCode)) continue;
      if (!codeToId.has(autoCode)) continue;
      seenAuto.add(autoCode);
      reasons.push({
        becauseOfCode,
        becauseOfName: codeToName.get(becauseOfCode) || becauseOfCode,
        autoCode,
        autoName: codeToName.get(autoCode) || autoCode,
      });
    }
  }

  return { nextIds, reasons };
}

/**
 * After turning OFF `turnedOffIds`, also remove any selected permission whose
 * required parents are no longer all selected (cascade off).
 */
export function applyPermissionDeselect(opts: {
  selectedIds: Set<number>;
  turnedOffIds: number[];
  idToCode: Map<number, string>;
  codeToId: Map<string, number>;
}): Set<number> {
  const { selectedIds, turnedOffIds, idToCode, codeToId } = opts;
  const turnedOff = new Set(turnedOffIds);

  const nextCodes = new Set(
    [...selectedIds]
      .filter((id) => !turnedOff.has(id))
      .map((id) => idToCode.get(id))
      .filter((c): c is string => !!c),
  );

  let changed = true;
  while (changed) {
    changed = false;
    for (const code of [...nextCodes]) {
      const missingParent = [...expandPermissionCodes([code])].some(
        (r) => r !== code && !nextCodes.has(r),
      );
      if (missingParent) {
        nextCodes.delete(code);
        changed = true;
      }
    }
  }

  const nextIds = new Set<number>();
  for (const code of nextCodes) {
    const id = codeToId.get(code);
    if (id != null) nextIds.add(id);
  }
  for (const id of selectedIds) {
    if (!idToCode.has(id) && !turnedOff.has(id)) nextIds.add(id);
  }
  return nextIds;
}
